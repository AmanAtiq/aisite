/**
 * Replaces placeholders or broken URLs with high-quality verified photos matching the topic.
 */
export function resolveProjectImages(files, prompt = "") {
  if (!files || typeof files !== "object") return files;

  // Extract explicit image URL from user prompt if provided
  const userUrlMatches =
    prompt.match(/https?:\/\/[^\s"'`<>]+\.(?:png|jpe?g|webp|gif|svg)(?:\?[^\s"'`<>]*)?/gi) ||
    prompt.match(/https:\/\/images\.unsplash\.com\/[^\s"'`<>]*/gi);
  const userImage = userUrlMatches ? userUrlMatches[0] : null;

  // Find general topic match for fallback
  const promptLower = prompt.toLowerCase();
  let defaultTopicImage = VERIFIED_IMAGES.workspace;
  for (const [key, url] of Object.entries(VERIFIED_IMAGES)) {
    if (promptLower.includes(key)) {
      defaultTopicImage = url;
      break;
    }
  }

  const updatedFiles = {};

  for (const [filePath, content] of Object.entries(files)) {
    if (typeof content !== "string") {
      updatedFiles[filePath] = content;
      continue;
    }

    let replaced = content;

    // 1. If user provided a specific image URL in prompt, inject into hero or first image
    if (userImage) {
      replaced = replaced.replace(
        /(<img[^>]*src=["'])(https?:\/\/[^"']+)(["'][^>]*>)/i,
        (match, prefix, oldUrl, suffix) => `${prefix}${userImage}${suffix}`
      );
    }

    // 2. Replace any placehold.co or broken placeholder hosts with verified topical photos
    replaced = replaced.replace(
      /(<img[^>]*src=["'])(https?:\/\/[^"']+)(["'][^>]*>)/gi,
      (fullMatch, prefix, url, suffix) => {
        // If it's already a verified unsplash photo, keep it!
        if (Object.values(VERIFIED_IMAGES).includes(url)) {
          return fullMatch;
        }

        // If it's placehold.co or broken host or fake unsplash URL
        const isPlaceholder =
          url.includes("placehold.co") ||
          url.includes("via.placeholder") ||
          url.includes("example.com");

        if (isPlaceholder) {
          const matchLower = fullMatch.toLowerCase();
          for (const [keyword, verifiedUrl] of Object.entries(VERIFIED_IMAGES)) {
            if (matchLower.includes(keyword)) {
              return `${prefix}${verifiedUrl}${suffix}`;
            }
          }
          return `${prefix}${defaultTopicImage}${suffix}`;
        }

        return fullMatch;
      }
    );

    // 3. Replace imageUrl: "https://placehold.co/..." in JS objects/arrays
    replaced = replaced.replace(
      /(imageUrl|image|src|img)\s*:\s*["'](https?:\/\/[^"']+)["']/gi,
      (fullMatch, prop, url) => {
        if (Object.values(VERIFIED_IMAGES).includes(url)) return fullMatch;
        if (url.includes("placehold.co") || url.includes("example.com")) {
          const matchLower = fullMatch.toLowerCase();
          for (const [keyword, verifiedUrl] of Object.entries(VERIFIED_IMAGES)) {
            if (matchLower.includes(keyword)) {
              return `${prop}: "${verifiedUrl}"`;
            }
          }
          return `${prop}: "${defaultTopicImage}"`;
        }
        return fullMatch;
      }
    );

    updatedFiles[filePath] = replaced;
  }

  return updatedFiles;
}

function normalizeProjectFiles(rawFiles, currentFiles = null, prompt = "") {
  if (!rawFiles) {
    throw new Error("Model returned no files.");
  }

  const files = {};
  if (Array.isArray(rawFiles)) {
    for (const f of rawFiles) {
      if (f && f.path && typeof f.content === "string") {
        let p = f.path.trim();
        if (!p.startsWith("/")) p = `/${p}`;
        files[p] = f.content;
      }
    }
  } else if (typeof rawFiles === "object") {
    for (const [p, content] of Object.entries(rawFiles)) {
      if (typeof content === "string") {
        let path = p.trim();
        if (!path.startsWith("/")) path = `/${path}`;
        files[path] = content;
      }
    }
  }

  // Normalize common path variations (e.g. if placed under /src/)
  if (!files["/App.js"]) {
    if (files["/src/App.js"]) {
      files["/App.js"] = files["/src/App.js"];
    } else if (files["/App.jsx"]) {
      files["/App.js"] = files["/App.jsx"];
    }
  }

  if (!files["/styles.css"]) {
    if (files["/src/styles.css"]) {
      files["/styles.css"] = files["/src/styles.css"];
    } else if (files["/src/App.css"]) {
      files["/styles.css"] = files["/src/App.css"];
    } else if (files["/App.css"]) {
      files["/styles.css"] = files["/App.css"];
    }
  }

  // Merge with existing project files so unchanged files are never dropped
  const mergedFiles = currentFiles ? { ...currentFiles, ...files } : files;

  if (Object.keys(mergedFiles).length === 0) {
    throw new Error("Model returned an empty files collection.");
  }
  if (!mergedFiles["/App.js"]) {
    throw new Error("Model's response is missing the required /App.js entry file.");
  }

  // Resolve and verify images
  return resolveProjectImages(mergedFiles, prompt);
}

export function getProviderConfig() {
  const geminiKey = process.env.GEMINI_API_KEY;
  const anthropicKey = process.env.ANTHROPIC_API_KEY;
  const envModel = process.env.MODEL;

  if (geminiKey) {
    return {
      provider: "gemini",
      apiKey: geminiKey,
      model: envModel || "gemini-2.5-flash",
    };
  }

  if (anthropicKey) {
    const isGeminiFormat =
      anthropicKey.startsWith("AQ.") ||
      anthropicKey.startsWith("AIza") ||
      (envModel && envModel.toLowerCase().startsWith("gemini"));

    if (isGeminiFormat) {
      return {
        provider: "gemini",
        apiKey: anthropicKey,
        model: envModel || "gemini-2.5-flash",
      };
    }

    return {
      provider: "anthropic",
      apiKey: anthropicKey,
      model: envModel || "claude-sonnet-5",
    };
  }

  return {
    provider: null,
    apiKey: null,
    model: null,
  };
}

async function callGeminiApi({ apiKey, model, contents }) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(apiKey)}`;

  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      contents,
      systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
      generationConfig: {
        responseMimeType: "application/json",
        responseSchema: {
          type: "OBJECT",
          properties: {
            summary: {
              type: "STRING",
              description: "One plain sentence describing what was built or changed.",
            },
            files: {
              type: "ARRAY",
              items: {
                type: "OBJECT",
                properties: {
                  path: {
                    type: "STRING",
                    description: "Root-level path starting with '/', e.g. /App.js, /styles.css, /components/Hero.js",
                  },
                  content: {
                    type: "STRING",
                    description: "Complete file code contents",
                  },
                },
                required: ["path", "content"],
              },
            },
          },
          required: ["summary", "files"],
        },
      },
    }),
  });

  const data = await res.json().catch(() => null);
  if (!res.ok || !data) {
    const errorMsg = data?.error?.message || `HTTP ${res.status}: ${res.statusText}`;
    const err = new Error(errorMsg);
    err.status = res.status;
    throw err;
  }

  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!rawText) {
    throw new Error("Gemini returned an empty response.");
  }

  return JSON.parse(rawText);
}

